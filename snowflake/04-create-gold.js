const { getConnection, connect, query } = require('./config');

async function run() {
  const conn = getConnection();
  await connect(conn);
  console.log('Connected. Creating Gold tables...\n');

  // ====================================================================
  // GOLD_CAMPAIGN_DAILY — Unified daily performance across ALL channels
  // ====================================================================
  console.log('Creating GOLD_CAMPAIGN_DAILY...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CAMPAIGN_DAILY AS
    -- Google Ads
    SELECT
      DATE, 'Google Ads' AS CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, CHANNEL_TYPE AS CAMPAIGN_TYPE,
      TARGET_GEO AS GEO, DAILY_BUDGET,
      SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS, SUM(SPEND) AS SPEND,
      SUM(CONVERSIONS) AS CONVERSIONS, SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(SPEND) / NULLIF(SUM(CLICKS), 0), 2) AS AVG_CPC,
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS
    FROM SILVER_V2.GOOGLE_ADS_PERFORMANCE
    GROUP BY DATE, CAMPAIGN_ID, CAMPAIGN_NAME, CHANNEL_TYPE, TARGET_GEO, DAILY_BUDGET

    UNION ALL

    -- Meta Ads
    SELECT
      DATE, 'Meta Ads' AS CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, OBJECTIVE AS CAMPAIGN_TYPE,
      TARGETING_GEO AS GEO, CAMPAIGN_DAILY_BUDGET AS DAILY_BUDGET,
      SUM(IMPRESSIONS), SUM(CLICKS), SUM(SPEND),
      SUM(CONVERSIONS), SUM(CONVERSION_VALUE),
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2),
      ROUND(SUM(SPEND) / NULLIF(SUM(CLICKS), 0), 2),
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2),
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2)
    FROM SILVER_V2.META_ADS_PERFORMANCE
    GROUP BY DATE, CAMPAIGN_ID, CAMPAIGN_NAME, OBJECTIVE, TARGETING_GEO, CAMPAIGN_DAILY_BUDGET

    UNION ALL

    -- Bing Ads
    SELECT
      DATE, 'Bing Ads' AS CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, 'SEARCH' AS CAMPAIGN_TYPE,
      CASE WHEN CAMPAIGN_NAME LIKE 'EU%' THEN 'EU' ELSE 'ES' END AS GEO, DAILY_BUDGET,
      SUM(IMPRESSIONS), SUM(CLICKS), SUM(SPEND),
      SUM(CONVERSIONS), SUM(CONVERSION_VALUE),
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2),
      ROUND(SUM(SPEND) / NULLIF(SUM(CLICKS), 0), 2),
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2),
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2)
    FROM SILVER_V2.BING_ADS_PERFORMANCE
    GROUP BY DATE, CAMPAIGN_ID, CAMPAIGN_NAME, DAILY_BUDGET
  `);

  // ====================================================================
  // GOLD_CHANNEL_DAILY — Aggregated by channel per day
  // ====================================================================
  console.log('Creating GOLD_CHANNEL_DAILY...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CHANNEL_DAILY AS
    SELECT
      DATE, CHANNEL,
      SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS, SUM(SPEND) AS SPEND,
      SUM(CONVERSIONS) AS CONVERSIONS, SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(SPEND) / NULLIF(SUM(CLICKS), 0), 2) AS AVG_CPC,
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
      SUM(DAILY_BUDGET) AS TOTAL_DAILY_BUDGET,
      ROUND(SUM(SPEND) / NULLIF(SUM(DAILY_BUDGET), 0) * 100, 2) AS BUDGET_UTILIZATION_PCT
    FROM GOLD.CAMPAIGN_DAILY
    GROUP BY DATE, CHANNEL
  `);

  // ====================================================================
  // GOLD_WEEKLY_TRENDS — Weekly aggregations for trend analysis
  // ====================================================================
  console.log('Creating GOLD_WEEKLY_TRENDS...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.WEEKLY_TRENDS AS
    SELECT
      DATE_TRUNC('WEEK', DATE) AS WEEK_START,
      CHANNEL,
      SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS, SUM(SPEND) AS SPEND,
      SUM(CONVERSIONS) AS CONVERSIONS, SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(SPEND) / NULLIF(SUM(CLICKS), 0), 2) AS AVG_CPC,
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
      -- WoW change
      LAG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('WEEK', DATE)) AS PREV_WEEK_SPEND,
      LAG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('WEEK', DATE)) AS PREV_WEEK_CONVERSIONS,
      ROUND((SUM(SPEND) - LAG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('WEEK', DATE)))
        / NULLIF(LAG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('WEEK', DATE)), 0) * 100, 1) AS SPEND_WOW_CHANGE_PCT,
      ROUND((SUM(CONVERSIONS) - LAG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('WEEK', DATE)))
        / NULLIF(LAG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('WEEK', DATE)), 0) * 100, 1) AS CONVERSIONS_WOW_CHANGE_PCT
    FROM GOLD.CAMPAIGN_DAILY
    GROUP BY DATE_TRUNC('WEEK', DATE), CHANNEL
  `);

  // ====================================================================
  // GOLD_MONTHLY_SUMMARY — Monthly aggregations + MoM comparison
  // ====================================================================
  console.log('Creating GOLD_MONTHLY_SUMMARY...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.MONTHLY_SUMMARY AS
    SELECT
      DATE_TRUNC('MONTH', DATE) AS MONTH,
      CHANNEL,
      SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS, SUM(SPEND) AS SPEND,
      SUM(CONVERSIONS) AS CONVERSIONS, SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(SPEND) / NULLIF(SUM(CLICKS), 0), 2) AS AVG_CPC,
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
      LAG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)) AS PREV_MONTH_SPEND,
      LAG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)) AS PREV_MONTH_CONVERSIONS,
      LAG(ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)) AS PREV_MONTH_ROAS,
      ROUND((SUM(SPEND) - LAG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)))
        / NULLIF(LAG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)), 0) * 100, 1) AS SPEND_MOM_CHANGE_PCT,
      ROUND((SUM(CONVERSIONS) - LAG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)))
        / NULLIF(LAG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE_TRUNC('MONTH', DATE)), 0) * 100, 1) AS CONVERSIONS_MOM_CHANGE_PCT
    FROM GOLD.CAMPAIGN_DAILY
    GROUP BY DATE_TRUNC('MONTH', DATE), CHANNEL
  `);

  // ====================================================================
  // GOLD_CAMPAIGN_RANKING — Best/worst campaigns with period comparison
  // ====================================================================
  console.log('Creating GOLD_CAMPAIGN_RANKING...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CAMPAIGN_RANKING AS
    WITH campaign_metrics AS (
      SELECT
        CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, CAMPAIGN_TYPE, GEO,
        DATE_TRUNC('MONTH', DATE) AS MONTH,
        SUM(SPEND) AS SPEND, SUM(CONVERSIONS) AS CONVERSIONS,
        SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
        SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS,
        ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
        ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS
      FROM GOLD.CAMPAIGN_DAILY
      GROUP BY CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, CAMPAIGN_TYPE, GEO, DATE_TRUNC('MONTH', DATE)
    )
    SELECT *,
      RANK() OVER (PARTITION BY MONTH, CHANNEL ORDER BY ROAS DESC) AS ROAS_RANK,
      RANK() OVER (PARTITION BY MONTH, CHANNEL ORDER BY CONVERSIONS DESC) AS CONVERSIONS_RANK,
      LAG(SPEND) OVER (PARTITION BY CAMPAIGN_ID ORDER BY MONTH) AS PREV_MONTH_SPEND,
      LAG(CONVERSIONS) OVER (PARTITION BY CAMPAIGN_ID ORDER BY MONTH) AS PREV_MONTH_CONVERSIONS,
      LAG(ROAS) OVER (PARTITION BY CAMPAIGN_ID ORDER BY MONTH) AS PREV_MONTH_ROAS
    FROM campaign_metrics
  `);

  // ====================================================================
  // GOLD_DEVICE_BREAKDOWN — Performance by device across channels
  // ====================================================================
  console.log('Creating GOLD_DEVICE_BREAKDOWN...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.DEVICE_BREAKDOWN AS
    SELECT
      DATE_TRUNC('MONTH', DATE) AS MONTH,
      'Google Ads' AS CHANNEL, DEVICE,
      SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS,
      SUM(SPEND) AS SPEND, SUM(CONVERSIONS) AS CONVERSIONS, SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS
    FROM SILVER_V2.GOOGLE_ADS_PERFORMANCE
    GROUP BY DATE_TRUNC('MONTH', DATE), DEVICE

    UNION ALL

    SELECT DATE_TRUNC('MONTH', DATE), 'Meta Ads', DEVICE_PLATFORM,
      SUM(IMPRESSIONS), SUM(CLICKS), SUM(SPEND), SUM(CONVERSIONS), SUM(CONVERSION_VALUE),
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2),
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2)
    FROM SILVER_V2.META_ADS_PERFORMANCE
    GROUP BY DATE_TRUNC('MONTH', DATE), DEVICE_PLATFORM

    UNION ALL

    SELECT DATE_TRUNC('MONTH', DATE), 'Bing Ads', DEVICE,
      SUM(IMPRESSIONS), SUM(CLICKS), SUM(SPEND), SUM(CONVERSIONS), SUM(CONVERSION_VALUE),
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2),
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2)
    FROM SILVER_V2.BING_ADS_PERFORMANCE
    GROUP BY DATE_TRUNC('MONTH', DATE), DEVICE
  `);

  // ====================================================================
  // GOLD_PLACEMENT_BREAKDOWN — Meta placement performance
  // ====================================================================
  console.log('Creating GOLD_PLACEMENT_BREAKDOWN...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.PLACEMENT_BREAKDOWN AS
    SELECT
      DATE_TRUNC('MONTH', DATE) AS MONTH,
      PUBLISHER_PLATFORM, PLACEMENT,
      SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS,
      SUM(SPEND) AS SPEND, SUM(CONVERSIONS) AS CONVERSIONS,
      SUM(CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(SPEND) / NULLIF(SUM(IMPRESSIONS), 0) * 1000, 2) AS CPM,
      ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
      SUM(REACH) AS REACH, ROUND(AVG(FREQUENCY), 2) AS AVG_FREQUENCY
    FROM SILVER_V2.META_ADS_PERFORMANCE
    GROUP BY DATE_TRUNC('MONTH', DATE), PUBLISHER_PLATFORM, PLACEMENT
  `);

  // ====================================================================
  // GOLD_CREATIVE_PERFORMANCE — Creative/ad level analysis
  // ====================================================================
  console.log('Creating GOLD_CREATIVE_PERFORMANCE...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CREATIVE_PERFORMANCE AS
    SELECT
      p.CAMPAIGN_NAME, p.ADSET_NAME, a.AD_NAME,
      cr.CREATIVE_NAME, cr.FORMAT, cr.CALL_TO_ACTION, cr.HEADLINE,
      SUM(p.IMPRESSIONS) AS IMPRESSIONS, SUM(p.CLICKS) AS CLICKS,
      SUM(p.SPEND) AS SPEND, SUM(p.CONVERSIONS) AS CONVERSIONS,
      SUM(p.CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(p.CLICKS) / NULLIF(SUM(p.IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(p.SPEND) / NULLIF(SUM(p.CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(p.CONVERSION_VALUE) / NULLIF(SUM(p.SPEND), 0), 2) AS ROAS
    FROM SILVER_V2.META_ADS_PERFORMANCE p
    LEFT JOIN SILVER_V2.META_ADS_ADS a ON p.AD_ID = a.AD_ID
    LEFT JOIN SILVER_V2.META_ADS_CREATIVES cr ON a.CREATIVE_ID = cr.CREATIVE_ID
    GROUP BY p.CAMPAIGN_NAME, p.ADSET_NAME, a.AD_NAME, cr.CREATIVE_NAME, cr.FORMAT, cr.CALL_TO_ACTION, cr.HEADLINE
  `);

  // ====================================================================
  // GOLD_KEYWORD_PERFORMANCE — Keyword level analysis (Google + Bing)
  // ====================================================================
  console.log('Creating GOLD_KEYWORD_PERFORMANCE...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.KEYWORD_PERFORMANCE AS
    SELECT
      'Google Ads' AS CHANNEL,
      p.CAMPAIGN_NAME, p.AD_GROUP_NAME,
      k.KEYWORD, k.MATCH_TYPE,
      SUM(p.IMPRESSIONS) AS IMPRESSIONS, SUM(p.CLICKS) AS CLICKS,
      SUM(p.SPEND) AS SPEND, SUM(p.CONVERSIONS) AS CONVERSIONS,
      SUM(p.CONVERSION_VALUE) AS CONVERSION_VALUE,
      ROUND(SUM(p.CLICKS) / NULLIF(SUM(p.IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(SUM(p.SPEND) / NULLIF(SUM(p.CLICKS), 0), 2) AS AVG_CPC,
      ROUND(SUM(p.SPEND) / NULLIF(SUM(p.CONVERSIONS), 0), 2) AS CPA,
      ROUND(SUM(p.CONVERSION_VALUE) / NULLIF(SUM(p.SPEND), 0), 2) AS ROAS
    FROM SILVER_V2.GOOGLE_ADS_PERFORMANCE p
    LEFT JOIN SILVER_V2.GOOGLE_ADS_KEYWORDS k ON p.KEYWORD_ID = k.KEYWORD_ID
    WHERE k.KEYWORD IS NOT NULL
    GROUP BY p.CAMPAIGN_NAME, p.AD_GROUP_NAME, k.KEYWORD, k.MATCH_TYPE

    UNION ALL

    SELECT
      'Bing Ads', p.CAMPAIGN_NAME, p.AD_GROUP_NAME,
      k.KEYWORD, k.MATCH_TYPE,
      SUM(p.IMPRESSIONS), SUM(p.CLICKS), SUM(p.SPEND), SUM(p.CONVERSIONS), SUM(p.CONVERSION_VALUE),
      ROUND(SUM(p.CLICKS) / NULLIF(SUM(p.IMPRESSIONS), 0) * 100, 2),
      ROUND(SUM(p.SPEND) / NULLIF(SUM(p.CLICKS), 0), 2),
      ROUND(SUM(p.SPEND) / NULLIF(SUM(p.CONVERSIONS), 0), 2),
      ROUND(SUM(p.CONVERSION_VALUE) / NULLIF(SUM(p.SPEND), 0), 2)
    FROM SILVER_V2.BING_ADS_PERFORMANCE p
    LEFT JOIN SILVER_V2.BING_ADS_KEYWORDS k ON p.KEYWORD_ID = k.KEYWORD_ID
    WHERE k.KEYWORD IS NOT NULL
    GROUP BY p.CAMPAIGN_NAME, p.AD_GROUP_NAME, k.KEYWORD, k.MATCH_TYPE
  `);

  // ====================================================================
  // GOLD_BUDGET_PACING — Budget spend vs allocation tracking
  // ====================================================================
  console.log('Creating GOLD_BUDGET_PACING...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.BUDGET_PACING AS
    WITH daily_spend AS (
      SELECT DATE, CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, DAILY_BUDGET, SPEND
      FROM GOLD.CAMPAIGN_DAILY
    ),
    monthly_pacing AS (
      SELECT
        DATE_TRUNC('MONTH', DATE) AS MONTH,
        CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME,
        AVG(DAILY_BUDGET) AS AVG_DAILY_BUDGET,
        AVG(DAILY_BUDGET) * DAY(LAST_DAY(DATE)) AS MONTHLY_BUDGET,
        SUM(SPEND) AS MONTHLY_SPEND,
        COUNT(DISTINCT DATE) AS DAYS_ACTIVE,
        DAY(LAST_DAY(DATE)) AS DAYS_IN_MONTH
      FROM daily_spend
      GROUP BY DATE_TRUNC('MONTH', DATE), CHANNEL, CAMPAIGN_ID, CAMPAIGN_NAME, LAST_DAY(DATE)
    )
    SELECT *,
      ROUND(MONTHLY_SPEND / NULLIF(MONTHLY_BUDGET, 0) * 100, 1) AS BUDGET_UTILIZATION_PCT,
      ROUND(MONTHLY_BUDGET - MONTHLY_SPEND, 2) AS REMAINING_BUDGET,
      CASE
        WHEN MONTHLY_SPEND / NULLIF(MONTHLY_BUDGET, 0) > 1.1 THEN 'OVERSPENDING'
        WHEN MONTHLY_SPEND / NULLIF(MONTHLY_BUDGET, 0) > 0.9 THEN 'ON_TRACK'
        WHEN MONTHLY_SPEND / NULLIF(MONTHLY_BUDGET, 0) > 0.7 THEN 'UNDERSPENDING'
        ELSE 'SEVERELY_UNDER'
      END AS PACING_STATUS
    FROM monthly_pacing
  `);

  // ====================================================================
  // GOLD_FUNNEL — Impression → Click → Conversion funnel by channel
  // ====================================================================
  console.log('Creating GOLD_FUNNEL...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.FUNNEL AS
    SELECT
      DATE_TRUNC('MONTH', DATE) AS MONTH,
      CHANNEL,
      SUM(IMPRESSIONS) AS TOTAL_IMPRESSIONS,
      SUM(CLICKS) AS TOTAL_CLICKS,
      SUM(CONVERSIONS) AS TOTAL_CONVERSIONS,
      SUM(CONVERSION_VALUE) AS TOTAL_VALUE,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS IMPRESSION_TO_CLICK_PCT,
      ROUND(SUM(CONVERSIONS) / NULLIF(SUM(CLICKS), 0) * 100, 2) AS CLICK_TO_CONVERSION_PCT,
      ROUND(SUM(CONVERSIONS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 4) AS IMPRESSION_TO_CONVERSION_PCT,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(CONVERSIONS), 0), 2) AS AVG_ORDER_VALUE
    FROM GOLD.CAMPAIGN_DAILY
    GROUP BY DATE_TRUNC('MONTH', DATE), CHANNEL
  `);

  // ====================================================================
  // GOLD_CHANGE_AUDIT — Unified change log across platforms
  // ====================================================================
  console.log('Creating GOLD_CHANGE_AUDIT...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CHANGE_AUDIT AS
    SELECT CHANGE_DATETIME, CHANGE_DATE, USER_EMAIL, PLATFORM,
           RESOURCE_TYPE, CHANGE_TYPE, CAMPAIGN_ID, CHANGED_FIELD, OLD_VALUE, NEW_VALUE
    FROM SILVER_V2.GOOGLE_ADS_CHANGE_HISTORY
    UNION ALL
    SELECT CHANGE_DATETIME, CHANGE_DATE, USER_EMAIL, PLATFORM,
           RESOURCE_TYPE, CHANGE_TYPE, CAMPAIGN_ID, CHANGED_FIELD, OLD_VALUE, NEW_VALUE
    FROM SILVER_V2.META_ADS_CHANGE_LOGS
  `);

  // ====================================================================
  // GOLD_GA4_OVERVIEW — Web analytics overview
  // ====================================================================
  console.log('Creating GOLD_GA4_OVERVIEW...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.GA4_OVERVIEW AS
    SELECT
      DATE_TRUNC('MONTH', DATE) AS MONTH,
      CHANNEL_GROUPING,
      SUM(SESSIONS) AS SESSIONS, SUM(ACTIVE_USERS) AS ACTIVE_USERS,
      SUM(ENGAGED_SESSIONS) AS ENGAGED_SESSIONS,
      SUM(CONVERSIONS) AS CONVERSIONS, SUM(TOTAL_REVENUE) AS REVENUE,
      ROUND(SUM(ENGAGED_SESSIONS) / NULLIF(SUM(SESSIONS), 0) * 100, 2) AS ENGAGEMENT_RATE_PCT,
      ROUND(SUM(CONVERSIONS) / NULLIF(SUM(SESSIONS), 0) * 100, 2) AS CONVERSION_RATE_PCT,
      ROUND(SUM(TOTAL_REVENUE) / NULLIF(SUM(SESSIONS), 0), 2) AS REVENUE_PER_SESSION,
      ROUND(AVG(AVG_SESSION_DURATION_SEC), 1) AS AVG_SESSION_DURATION_SEC
    FROM SILVER_V2.GA4_SESSIONS
    GROUP BY DATE_TRUNC('MONTH', DATE), CHANNEL_GROUPING
  `);

  // ====================================================================
  // GOLD_GA4_DAILY — Daily web traffic for trendlines
  // ====================================================================
  console.log('Creating GOLD_GA4_DAILY...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.GA4_DAILY AS
    SELECT
      DATE,
      SUM(SESSIONS) AS SESSIONS, SUM(ACTIVE_USERS) AS ACTIVE_USERS,
      SUM(ENGAGED_SESSIONS) AS ENGAGED_SESSIONS,
      SUM(CONVERSIONS) AS CONVERSIONS, SUM(TOTAL_REVENUE) AS REVENUE,
      ROUND(SUM(ENGAGED_SESSIONS) / NULLIF(SUM(SESSIONS), 0) * 100, 2) AS ENGAGEMENT_RATE_PCT,
      ROUND(SUM(CONVERSIONS) / NULLIF(SUM(SESSIONS), 0) * 100, 2) AS CONVERSION_RATE_PCT
    FROM SILVER_V2.GA4_SESSIONS
    GROUP BY DATE
  `);

  // ====================================================================
  // GOLD_SEO_PERFORMANCE — GSC search performance
  // ====================================================================
  console.log('Creating GOLD_SEO_PERFORMANCE...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.SEO_PERFORMANCE AS
    SELECT
      DATE_TRUNC('MONTH', DATE) AS MONTH,
      QUERY,
      SUM(CLICKS) AS CLICKS, SUM(IMPRESSIONS) AS IMPRESSIONS,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(AVG(AVG_POSITION), 1) AS AVG_POSITION,
      LAG(SUM(CLICKS)) OVER (PARTITION BY QUERY ORDER BY DATE_TRUNC('MONTH', DATE)) AS PREV_MONTH_CLICKS,
      LAG(ROUND(AVG(AVG_POSITION), 1)) OVER (PARTITION BY QUERY ORDER BY DATE_TRUNC('MONTH', DATE)) AS PREV_MONTH_POSITION
    FROM SILVER_V2.GSC_PERFORMANCE
    GROUP BY DATE_TRUNC('MONTH', DATE), QUERY
  `);

  // ====================================================================
  // GOLD_SEO_DAILY — Daily SEO for trendlines
  // ====================================================================
  console.log('Creating GOLD_SEO_DAILY...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.SEO_DAILY AS
    SELECT
      DATE,
      SUM(CLICKS) AS CLICKS, SUM(IMPRESSIONS) AS IMPRESSIONS,
      ROUND(SUM(CLICKS) / NULLIF(SUM(IMPRESSIONS), 0) * 100, 2) AS CTR_PCT,
      ROUND(AVG(AVG_POSITION), 1) AS AVG_POSITION
    FROM SILVER_V2.GSC_PERFORMANCE
    GROUP BY DATE
  `);

  // ====================================================================
  // GOLD_CRM_PIPELINE — Sales pipeline analysis
  // ====================================================================
  console.log('Creating GOLD_CRM_PIPELINE...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CRM_PIPELINE AS
    SELECT
      STAGE, DEAL_STATUS, DEAL_SIZE, INDUSTRY, COUNTRY, LEAD_SOURCE,
      COUNT(*) AS NUM_DEALS,
      SUM(AMOUNT) AS TOTAL_VALUE,
      ROUND(AVG(AMOUNT), 2) AS AVG_DEAL_SIZE,
      ROUND(AVG(PROBABILITY), 1) AS AVG_PROBABILITY,
      SUM(AMOUNT * PROBABILITY / 100) AS WEIGHTED_VALUE
    FROM SILVER_V2.CRM_PIPELINE
    GROUP BY STAGE, DEAL_STATUS, DEAL_SIZE, INDUSTRY, COUNTRY, LEAD_SOURCE
  `);

  // ====================================================================
  // GOLD_CRM_LEAD_FUNNEL — Lead conversion analysis
  // ====================================================================
  console.log('Creating GOLD_CRM_LEAD_FUNNEL...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.CRM_LEAD_FUNNEL AS
    SELECT
      LEAD_SOURCE,
      COUNT(*) AS TOTAL_LEADS,
      SUM(CASE WHEN STATUS = 'Qualified' OR IS_CONVERTED THEN 1 ELSE 0 END) AS QUALIFIED_LEADS,
      SUM(CASE WHEN IS_CONVERTED THEN 1 ELSE 0 END) AS CONVERTED_LEADS,
      ROUND(SUM(CASE WHEN IS_CONVERTED THEN 1 ELSE 0 END) / NULLIF(COUNT(*), 0) * 100, 1) AS CONVERSION_RATE_PCT
    FROM SILVER_V2.CRM_LEADS
    GROUP BY LEAD_SOURCE
  `);

  // ====================================================================
  // GOLD_FORECAST_BASE — Clean daily series for forecasting models
  // ====================================================================
  console.log('Creating GOLD_FORECAST_BASE...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.FORECAST_BASE AS
    SELECT
      DATE,
      CHANNEL,
      SUM(SPEND) AS SPEND,
      SUM(CONVERSIONS) AS CONVERSIONS,
      SUM(CONVERSION_VALUE) AS REVENUE,
      ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
      DAYOFWEEK(DATE) AS DAY_OF_WEEK,
      DAYOFMONTH(DATE) AS DAY_OF_MONTH,
      MONTH(DATE) AS MONTH_NUM,
      WEEKOFYEAR(DATE) AS WEEK_NUM,
      -- Rolling 7-day averages
      ROUND(AVG(SUM(SPEND)) OVER (PARTITION BY CHANNEL ORDER BY DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW), 2) AS SPEND_7D_AVG,
      ROUND(AVG(SUM(CONVERSIONS)) OVER (PARTITION BY CHANNEL ORDER BY DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW), 2) AS CONVERSIONS_7D_AVG,
      ROUND(AVG(SUM(CONVERSION_VALUE)) OVER (PARTITION BY CHANNEL ORDER BY DATE ROWS BETWEEN 6 PRECEDING AND CURRENT ROW), 2) AS REVENUE_7D_AVG
    FROM GOLD.CAMPAIGN_DAILY
    GROUP BY DATE, CHANNEL
  `);

  // ====================================================================
  // GOLD_EXECUTIVE_KPI — Top-level KPIs for dashboard
  // ====================================================================
  console.log('Creating GOLD_EXECUTIVE_KPI...');
  await query(conn, `CREATE OR REPLACE TABLE GOLD.EXECUTIVE_KPI AS
    WITH current_month AS (
      SELECT
        SUM(SPEND) AS SPEND, SUM(CONVERSIONS) AS CONVERSIONS,
        SUM(CONVERSION_VALUE) AS REVENUE,
        ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
        ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA,
        SUM(IMPRESSIONS) AS IMPRESSIONS, SUM(CLICKS) AS CLICKS
      FROM GOLD.CAMPAIGN_DAILY
      WHERE DATE >= DATE_TRUNC('MONTH', CURRENT_DATE())
    ),
    prev_month AS (
      SELECT
        SUM(SPEND) AS SPEND, SUM(CONVERSIONS) AS CONVERSIONS,
        SUM(CONVERSION_VALUE) AS REVENUE,
        ROUND(SUM(CONVERSION_VALUE) / NULLIF(SUM(SPEND), 0), 2) AS ROAS,
        ROUND(SUM(SPEND) / NULLIF(SUM(CONVERSIONS), 0), 2) AS CPA
      FROM GOLD.CAMPAIGN_DAILY
      WHERE DATE >= DATEADD(MONTH, -1, DATE_TRUNC('MONTH', CURRENT_DATE()))
        AND DATE < DATE_TRUNC('MONTH', CURRENT_DATE())
    )
    SELECT
      c.SPEND AS CURRENT_SPEND, c.CONVERSIONS AS CURRENT_CONVERSIONS,
      c.REVENUE AS CURRENT_REVENUE, c.ROAS AS CURRENT_ROAS, c.CPA AS CURRENT_CPA,
      c.IMPRESSIONS AS CURRENT_IMPRESSIONS, c.CLICKS AS CURRENT_CLICKS,
      p.SPEND AS PREV_SPEND, p.CONVERSIONS AS PREV_CONVERSIONS,
      p.REVENUE AS PREV_REVENUE, p.ROAS AS PREV_ROAS, p.CPA AS PREV_CPA,
      ROUND((c.SPEND - p.SPEND) / NULLIF(p.SPEND, 0) * 100, 1) AS SPEND_CHANGE_PCT,
      ROUND((c.CONVERSIONS - p.CONVERSIONS) / NULLIF(p.CONVERSIONS, 0) * 100, 1) AS CONVERSIONS_CHANGE_PCT,
      ROUND((c.REVENUE - p.REVENUE) / NULLIF(p.REVENUE, 0) * 100, 1) AS REVENUE_CHANGE_PCT
    FROM current_month c, prev_month p
  `);

  conn.destroy();
  console.log('\nAll Gold tables created!');
}

