const { getConnection, connect, query } = require('./config');

async function run() {
  const conn = getConnection();
  await connect(conn);
  console.log('Connected. Creating Silver tables...\n');

  // ====== GOOGLE ADS SILVER ======
  console.log('Creating Google Ads Silver tables...');

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GOOGLE_ADS_CAMPAIGNS AS
    SELECT CAMPAIGN_ID, CAMPAIGN_NAME, STATUS, CHANNEL_TYPE, BUDGET, BUDGET_TYPE,
           BIDDING_STRATEGY, START_DATE, END_DATE, TARGET_GEO, _LOADED_AT, _SOURCE
    FROM BRONZE_V2.GOOGLE_ADS_CAMPAIGNS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GOOGLE_ADS_AD_GROUPS AS
    SELECT AD_GROUP_ID, AD_GROUP_NAME, CAMPAIGN_ID, STATUS, MAX_CPC, AD_GROUP_TYPE, _LOADED_AT
    FROM BRONZE_V2.GOOGLE_ADS_AD_GROUPS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GOOGLE_ADS_ADS AS
    SELECT AD_ID, AD_GROUP_ID, AD_TYPE, FINAL_URL, HEADLINE_1, HEADLINE_2, HEADLINE_3,
           DESCRIPTION_1, DESCRIPTION_2, STATUS, _LOADED_AT
    FROM BRONZE_V2.GOOGLE_ADS_ADS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GOOGLE_ADS_KEYWORDS AS
    SELECT KEYWORD_ID, AD_GROUP_ID, KEYWORD, MATCH_TYPE, STATUS, MAX_CPC, _LOADED_AT
    FROM BRONZE_V2.GOOGLE_ADS_KEYWORDS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GOOGLE_ADS_PERFORMANCE AS
    SELECT
      p.DATE, p.CAMPAIGN_ID, c.CAMPAIGN_NAME, c.STATUS AS CAMPAIGN_STATUS,
      c.CHANNEL_TYPE, c.BUDGET AS DAILY_BUDGET, c.BIDDING_STRATEGY, c.TARGET_GEO,
      p.AD_GROUP_ID, ag.AD_GROUP_NAME, ag.AD_GROUP_TYPE,
      p.KEYWORD_ID, p.DEVICE,
      p.IMPRESSIONS, p.CLICKS, p.COST AS SPEND, p.CONVERSIONS, p.CONVERSION_VALUE,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.CLICKS / p.IMPRESSIONS * 100 ELSE 0 END, 2) AS CTR_PCT,
      ROUND(CASE WHEN p.CLICKS > 0 THEN p.COST / p.CLICKS ELSE 0 END, 2) AS AVG_CPC,
      ROUND(CASE WHEN p.CONVERSIONS > 0 THEN p.COST / p.CONVERSIONS ELSE 0 END, 2) AS COST_PER_CONVERSION,
      ROUND(CASE WHEN p.COST > 0 THEN p.CONVERSION_VALUE / p.COST ELSE 0 END, 2) AS ROAS,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.CONVERSIONS / p.IMPRESSIONS * 100 ELSE 0 END, 4) AS CONV_RATE_PCT,
      p._LOADED_AT
    FROM BRONZE_V2.GOOGLE_ADS_PERFORMANCE p
    LEFT JOIN BRONZE_V2.GOOGLE_ADS_CAMPAIGNS c ON p.CAMPAIGN_ID = c.CAMPAIGN_ID
    LEFT JOIN BRONZE_V2.GOOGLE_ADS_AD_GROUPS ag ON p.AD_GROUP_ID = ag.AD_GROUP_ID`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GOOGLE_ADS_CHANGE_HISTORY AS
    SELECT CHANGE_DATETIME, DATE(CHANGE_DATETIME) AS CHANGE_DATE,
           USER_EMAIL, RESOURCE_TYPE, CHANGE_TYPE, RESOURCE_ID,
           CAMPAIGN_ID, AD_GROUP_ID, CHANGED_FIELD, OLD_VALUE, NEW_VALUE,
           _LOADED_AT, 'google_ads' AS PLATFORM
    FROM BRONZE_V2.GOOGLE_ADS_CHANGE_HISTORY`);

  // ====== META ADS SILVER ======
  console.log('Creating Meta Ads Silver tables...');

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.META_ADS_CAMPAIGNS AS
    SELECT CAMPAIGN_ID, CAMPAIGN_NAME, OBJECTIVE, STATUS, DAILY_BUDGET, LIFETIME_BUDGET,
           START_DATE, STOP_DATE,
           DATEDIFF(DAY, START_DATE, COALESCE(STOP_DATE, CURRENT_DATE())) AS CAMPAIGN_DURATION_DAYS,
           _LOADED_AT, _SOURCE
    FROM BRONZE_V2.META_ADS_CAMPAIGNS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.META_ADS_AD_SETS AS
    SELECT ADSET_ID, ADSET_NAME, CAMPAIGN_ID, OPTIMIZATION_GOAL, BILLING_EVENT,
           STATUS, DAILY_BUDGET, TARGETING_GEO, TARGETING_AGES, _LOADED_AT
    FROM BRONZE_V2.META_ADS_AD_SETS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.META_ADS_ADS AS
    SELECT a.AD_ID, a.AD_NAME, a.ADSET_ID, a.CREATIVE_ID, a.STATUS, a._LOADED_AT
    FROM BRONZE_V2.META_ADS_ADS a`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.META_ADS_CREATIVES AS
    SELECT CREATIVE_ID, CREATIVE_NAME, HEADLINE, BODY_TEXT, CALL_TO_ACTION,
           IMAGE_URL, VIDEO_URL, FORMAT, _LOADED_AT
    FROM BRONZE_V2.META_ADS_CREATIVES`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.META_ADS_PERFORMANCE AS
    SELECT
      p.DATE, p.CAMPAIGN_ID, c.CAMPAIGN_NAME, c.OBJECTIVE, c.STATUS AS CAMPAIGN_STATUS,
      c.DAILY_BUDGET AS CAMPAIGN_DAILY_BUDGET,
      p.ADSET_ID, ads.ADSET_NAME, ads.OPTIMIZATION_GOAL, ads.TARGETING_GEO,
      p.AD_ID, p.DEVICE_PLATFORM, p.PUBLISHER_PLATFORM, p.PLACEMENT,
      p.IMPRESSIONS, p.CLICKS, p.SPEND, p.CONVERSIONS, p.CONVERSION_VALUE,
      p.REACH, p.FREQUENCY,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.CLICKS / p.IMPRESSIONS * 100 ELSE 0 END, 2) AS CTR_PCT,
      ROUND(CASE WHEN p.CLICKS > 0 THEN p.SPEND / p.CLICKS ELSE 0 END, 2) AS CPC,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.SPEND / p.IMPRESSIONS * 1000 ELSE 0 END, 2) AS CPM,
      ROUND(CASE WHEN p.CONVERSIONS > 0 THEN p.SPEND / p.CONVERSIONS ELSE 0 END, 2) AS COST_PER_CONVERSION,
      ROUND(CASE WHEN p.SPEND > 0 THEN p.CONVERSION_VALUE / p.SPEND ELSE 0 END, 2) AS ROAS,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.CONVERSIONS / p.IMPRESSIONS * 100 ELSE 0 END, 4) AS CONV_RATE_PCT,
      p._LOADED_AT
    FROM BRONZE_V2.META_ADS_PERFORMANCE p
    LEFT JOIN BRONZE_V2.META_ADS_CAMPAIGNS c ON p.CAMPAIGN_ID = c.CAMPAIGN_ID
    LEFT JOIN BRONZE_V2.META_ADS_AD_SETS ads ON p.ADSET_ID = ads.ADSET_ID`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.META_ADS_CHANGE_LOGS AS
    SELECT CHANGE_DATETIME, DATE(CHANGE_DATETIME) AS CHANGE_DATE,
           USER_EMAIL, RESOURCE_TYPE, CHANGE_TYPE, RESOURCE_ID,
           CAMPAIGN_ID, ADSET_ID, CHANGED_FIELD, OLD_VALUE, NEW_VALUE,
           _LOADED_AT, 'meta_ads' AS PLATFORM
    FROM BRONZE_V2.META_ADS_CHANGE_LOGS`);

  // ====== BING ADS SILVER ======
  console.log('Creating Bing Ads Silver tables...');

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.BING_ADS_CAMPAIGNS AS
    SELECT CAMPAIGN_ID, CAMPAIGN_NAME, STATUS, BUDGET, BUDGET_TYPE, TIMEZONE, CREATED_DATE, _LOADED_AT
    FROM BRONZE_V2.BING_ADS_CAMPAIGNS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.BING_ADS_AD_GROUPS AS
    SELECT AD_GROUP_ID, AD_GROUP_NAME, CAMPAIGN_ID, STATUS, CPC_BID, _LOADED_AT
    FROM BRONZE_V2.BING_ADS_AD_GROUPS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.BING_ADS_KEYWORDS AS
    SELECT KEYWORD_ID, AD_GROUP_ID, KEYWORD, MATCH_TYPE, BID, STATUS, _LOADED_AT
    FROM BRONZE_V2.BING_ADS_KEYWORDS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.BING_ADS_PERFORMANCE AS
    SELECT
      p.DATE, p.CAMPAIGN_ID, c.CAMPAIGN_NAME, c.STATUS AS CAMPAIGN_STATUS,
      c.BUDGET AS DAILY_BUDGET,
      p.AD_GROUP_ID, ag.AD_GROUP_NAME,
      p.KEYWORD_ID, p.DEVICE,
      p.IMPRESSIONS, p.CLICKS, p.SPEND, p.CONVERSIONS, p.CONVERSION_VALUE,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.CLICKS / p.IMPRESSIONS * 100 ELSE 0 END, 2) AS CTR_PCT,
      ROUND(CASE WHEN p.CLICKS > 0 THEN p.SPEND / p.CLICKS ELSE 0 END, 2) AS AVG_CPC,
      ROUND(CASE WHEN p.CONVERSIONS > 0 THEN p.SPEND / p.CONVERSIONS ELSE 0 END, 2) AS COST_PER_CONVERSION,
      ROUND(CASE WHEN p.SPEND > 0 THEN p.CONVERSION_VALUE / p.SPEND ELSE 0 END, 2) AS ROAS,
      ROUND(CASE WHEN p.IMPRESSIONS > 0 THEN p.CONVERSIONS / p.IMPRESSIONS * 100 ELSE 0 END, 4) AS CONV_RATE_PCT,
      p._LOADED_AT
    FROM BRONZE_V2.BING_ADS_PERFORMANCE p
    LEFT JOIN BRONZE_V2.BING_ADS_CAMPAIGNS c ON p.CAMPAIGN_ID = c.CAMPAIGN_ID
    LEFT JOIN BRONZE_V2.BING_ADS_AD_GROUPS ag ON p.AD_GROUP_ID = ag.AD_GROUP_ID`);

  // ====== GA4 SILVER ======
  console.log('Creating GA4 Silver tables...');

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GA4_SESSIONS AS
    SELECT
      DATE, COUNTRY, DEVICE_CATEGORY, SESSION_SOURCE, SESSION_MEDIUM, CAMPAIGN_NAME,
      EVENT_NAME, ACTIVE_USERS, SESSIONS, ENGAGED_SESSIONS, EVENT_COUNT, CONVERSIONS,
      TOTAL_REVENUE, ENGAGEMENT_RATE,
      ROUND(AVG_SESSION_DURATION, 1) AS AVG_SESSION_DURATION_SEC,
      ROUND(AVG_SESSION_DURATION / 60.0, 2) AS AVG_SESSION_DURATION_MIN,
      ROUND(CASE WHEN SESSIONS > 0 THEN CONVERSIONS / SESSIONS * 100 ELSE 0 END, 2) AS CONVERSION_RATE_PCT,
      ROUND(CASE WHEN SESSIONS > 0 THEN TOTAL_REVENUE / SESSIONS ELSE 0 END, 2) AS REVENUE_PER_SESSION,
      ROUND(CASE WHEN SESSIONS > 0 THEN EVENT_COUNT / SESSIONS ELSE 0 END, 2) AS EVENTS_PER_SESSION,
      CASE
        WHEN SESSION_MEDIUM = 'cpc' THEN 'Paid Search'
        WHEN SESSION_MEDIUM = 'organic' THEN 'Organic Search'
        WHEN SESSION_MEDIUM = 'email' THEN 'Email'
        WHEN SESSION_MEDIUM = '(none)' AND SESSION_SOURCE = 'direct' THEN 'Direct'
        WHEN SESSION_MEDIUM = 'referral' THEN 'Referral'
        ELSE 'Other'
      END AS CHANNEL_GROUPING,
      _LOADED_AT
    FROM BRONZE_V2.GA4_EVENTS`);

  // ====== GSC SILVER ======
  console.log('Creating GSC Silver tables...');

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.GSC_PERFORMANCE AS
    SELECT
      DATE, QUERY, PAGE, COUNTRY, DEVICE,
      CLICKS, IMPRESSIONS,
      ROUND(CTR * 100, 2) AS CTR_PCT,
      ROUND(POSITION, 1) AS AVG_POSITION,
      _LOADED_AT
    FROM BRONZE_V2.GSC_PERFORMANCE`);

  // ====== CRM SILVER ======
  console.log('Creating CRM Silver tables...');

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.CRM_ACCOUNTS AS
    SELECT * FROM BRONZE_V2.CRM_ACCOUNTS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.CRM_CONTACTS AS
    SELECT * FROM BRONZE_V2.CRM_CONTACTS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.CRM_LEADS AS
    SELECT *, CASE WHEN CONVERTED_DATE IS NOT NULL THEN TRUE ELSE FALSE END AS IS_CONVERTED
    FROM BRONZE_V2.CRM_LEADS`);

  await query(conn, `CREATE OR REPLACE TABLE SILVER_V2.CRM_PIPELINE AS
    SELECT
      o.OPPORTUNITY_ID, o.OPPORTUNITY_NAME, o.ACCOUNT_ID,
      a.ACCOUNT_NAME, a.INDUSTRY, a.COUNTRY,
      o.STAGE, o.AMOUNT, o.CLOSE_DATE, o.PROBABILITY, o.LEAD_SOURCE,
      o.CREATED_DATE, o.LAST_MODIFIED_DATE, o.OWNER_ID,
      CASE
        WHEN o.STAGE = 'Closed Won' THEN 'Won'
        WHEN o.STAGE = 'Closed Lost' THEN 'Lost'
        ELSE 'Open'
      END AS DEAL_STATUS,
      CASE
        WHEN o.AMOUNT < 10000 THEN 'Small'
        WHEN o.AMOUNT < 50000 THEN 'Medium'
        WHEN o.AMOUNT < 100000 THEN 'Large'
        ELSE 'Enterprise'
      END AS DEAL_SIZE,
      o._LOADED_AT
    FROM BRONZE_V2.CRM_OPPORTUNITIES o
    LEFT JOIN BRONZE_V2.CRM_ACCOUNTS a ON o.ACCOUNT_ID = a.ACCOUNT_ID`);

  conn.destroy();
  console.log('\nAll Silver tables created!');
}

run().catch(err => { console.error('Error:', err.message); process.exit(1); });
