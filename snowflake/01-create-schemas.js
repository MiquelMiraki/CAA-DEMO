const { getConnection, connect, query } = require('./config');

async function run() {
  const conn = getConnection();
  await connect(conn);
  console.log('Connected. Creating schemas...\n');

  // Create schemas
  await query(conn, 'CREATE SCHEMA IF NOT EXISTS CAA_DB.BRONZE_V2');
  console.log('Created BRONZE_V2');
  await query(conn, 'CREATE SCHEMA IF NOT EXISTS CAA_DB.SILVER_V2');
  console.log('Created SILVER_V2');
  await query(conn, 'CREATE SCHEMA IF NOT EXISTS CAA_DB.GOLD');
  console.log('Created GOLD');

  // ========== BRONZE TABLES ==========
  console.log('\n--- Creating Bronze tables ---');

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GOOGLE_ADS_CAMPAIGNS (
    CAMPAIGN_ID NUMBER, CAMPAIGN_NAME TEXT, STATUS TEXT, CHANNEL_TYPE TEXT,
    BUDGET FLOAT, BUDGET_TYPE TEXT, BIDDING_STRATEGY TEXT,
    START_DATE DATE, END_DATE DATE, TARGET_GEO TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'google_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GOOGLE_ADS_AD_GROUPS (
    AD_GROUP_ID NUMBER, AD_GROUP_NAME TEXT, CAMPAIGN_ID NUMBER,
    STATUS TEXT, MAX_CPC FLOAT, AD_GROUP_TYPE TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'google_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GOOGLE_ADS_ADS (
    AD_ID NUMBER, AD_GROUP_ID NUMBER, AD_TYPE TEXT, FINAL_URL TEXT,
    HEADLINE_1 TEXT, HEADLINE_2 TEXT, HEADLINE_3 TEXT,
    DESCRIPTION_1 TEXT, DESCRIPTION_2 TEXT, STATUS TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'google_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GOOGLE_ADS_KEYWORDS (
    KEYWORD_ID NUMBER, AD_GROUP_ID NUMBER, KEYWORD TEXT,
    MATCH_TYPE TEXT, STATUS TEXT, MAX_CPC FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'google_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GOOGLE_ADS_PERFORMANCE (
    DATE DATE, CAMPAIGN_ID NUMBER, AD_GROUP_ID NUMBER, KEYWORD_ID NUMBER,
    DEVICE TEXT, IMPRESSIONS NUMBER, CLICKS NUMBER, COST FLOAT,
    CONVERSIONS NUMBER, CONVERSION_VALUE FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'google_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GOOGLE_ADS_CHANGE_HISTORY (
    CHANGE_DATETIME TIMESTAMP_NTZ, USER_EMAIL TEXT, RESOURCE_TYPE TEXT,
    CHANGE_TYPE TEXT, RESOURCE_ID NUMBER, CAMPAIGN_ID NUMBER,
    AD_GROUP_ID NUMBER, CHANGED_FIELD TEXT, OLD_VALUE TEXT, NEW_VALUE TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'google_ads_api'
  )`);

  // Meta Ads
  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.META_ADS_CAMPAIGNS (
    CAMPAIGN_ID NUMBER, CAMPAIGN_NAME TEXT, OBJECTIVE TEXT,
    STATUS TEXT, DAILY_BUDGET FLOAT, LIFETIME_BUDGET FLOAT,
    START_DATE DATE, STOP_DATE DATE,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'meta_marketing_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.META_ADS_AD_SETS (
    ADSET_ID NUMBER, ADSET_NAME TEXT, CAMPAIGN_ID NUMBER,
    OPTIMIZATION_GOAL TEXT, BILLING_EVENT TEXT, STATUS TEXT,
    DAILY_BUDGET FLOAT, TARGETING_GEO TEXT, TARGETING_AGES TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'meta_marketing_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.META_ADS_ADS (
    AD_ID NUMBER, AD_NAME TEXT, ADSET_ID NUMBER, CREATIVE_ID NUMBER, STATUS TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'meta_marketing_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.META_ADS_CREATIVES (
    CREATIVE_ID NUMBER, CREATIVE_NAME TEXT, HEADLINE TEXT,
    BODY_TEXT TEXT, CALL_TO_ACTION TEXT, IMAGE_URL TEXT, VIDEO_URL TEXT,
    FORMAT TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'meta_marketing_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.META_ADS_PERFORMANCE (
    DATE DATE, CAMPAIGN_ID NUMBER, ADSET_ID NUMBER, AD_ID NUMBER,
    DEVICE_PLATFORM TEXT, PUBLISHER_PLATFORM TEXT, PLACEMENT TEXT,
    IMPRESSIONS NUMBER, CLICKS NUMBER, SPEND FLOAT,
    CONVERSIONS NUMBER, CONVERSION_VALUE FLOAT,
    REACH NUMBER, FREQUENCY FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'meta_marketing_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.META_ADS_CHANGE_LOGS (
    CHANGE_DATETIME TIMESTAMP_NTZ, USER_EMAIL TEXT, RESOURCE_TYPE TEXT,
    CHANGE_TYPE TEXT, RESOURCE_ID NUMBER, CAMPAIGN_ID NUMBER,
    ADSET_ID NUMBER, CHANGED_FIELD TEXT, OLD_VALUE TEXT, NEW_VALUE TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'meta_marketing_api'
  )`);

  // Bing Ads
  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.BING_ADS_CAMPAIGNS (
    CAMPAIGN_ID NUMBER, CAMPAIGN_NAME TEXT, STATUS TEXT,
    BUDGET FLOAT, BUDGET_TYPE TEXT, TIMEZONE TEXT, CREATED_DATE DATE,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'bing_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.BING_ADS_AD_GROUPS (
    AD_GROUP_ID NUMBER, AD_GROUP_NAME TEXT, CAMPAIGN_ID NUMBER,
    STATUS TEXT, CPC_BID FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'bing_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.BING_ADS_KEYWORDS (
    KEYWORD_ID NUMBER, AD_GROUP_ID NUMBER, KEYWORD TEXT,
    MATCH_TYPE TEXT, BID FLOAT, STATUS TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'bing_ads_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.BING_ADS_PERFORMANCE (
    DATE DATE, CAMPAIGN_ID NUMBER, AD_GROUP_ID NUMBER, KEYWORD_ID NUMBER,
    DEVICE TEXT, IMPRESSIONS NUMBER, CLICKS NUMBER, SPEND FLOAT,
    CONVERSIONS NUMBER, CONVERSION_VALUE FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'bing_ads_api'
  )`);

  // GA4
  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GA4_EVENTS (
    DATE DATE, COUNTRY TEXT, DEVICE_CATEGORY TEXT,
    SESSION_SOURCE TEXT, SESSION_MEDIUM TEXT, CAMPAIGN_NAME TEXT,
    EVENT_NAME TEXT, ACTIVE_USERS NUMBER, SESSIONS NUMBER,
    ENGAGED_SESSIONS NUMBER, EVENT_COUNT NUMBER, CONVERSIONS NUMBER,
    TOTAL_REVENUE FLOAT, ENGAGEMENT_RATE FLOAT, AVG_SESSION_DURATION FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'ga4_data_api'
  )`);

  // GSC
  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.GSC_PERFORMANCE (
    DATE DATE, QUERY TEXT, PAGE TEXT, COUNTRY TEXT, DEVICE TEXT,
    CLICKS NUMBER, IMPRESSIONS NUMBER, CTR FLOAT, POSITION FLOAT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'gsc_api'
  )`);

  // Salesforce / CRM
  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.CRM_ACCOUNTS (
    ACCOUNT_ID TEXT, ACCOUNT_NAME TEXT, INDUSTRY TEXT,
    WEBSITE TEXT, COUNTRY TEXT, CITY TEXT,
    ANNUAL_REVENUE FLOAT, EMPLOYEE_COUNT NUMBER, CREATED_DATE DATE,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'salesforce_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.CRM_CONTACTS (
    CONTACT_ID TEXT, FIRST_NAME TEXT, LAST_NAME TEXT,
    EMAIL TEXT, PHONE TEXT, ACCOUNT_ID TEXT, JOB_TITLE TEXT,
    CREATED_DATE DATE,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'salesforce_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.CRM_LEADS (
    LEAD_ID TEXT, FIRST_NAME TEXT, LAST_NAME TEXT,
    COMPANY TEXT, EMAIL TEXT, LEAD_SOURCE TEXT, STATUS TEXT,
    INDUSTRY TEXT, COUNTRY TEXT, CREATED_DATE DATE, CONVERTED_DATE DATE,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'salesforce_api'
  )`);

  await query(conn, `CREATE OR REPLACE TABLE BRONZE_V2.CRM_OPPORTUNITIES (
    OPPORTUNITY_ID TEXT, OPPORTUNITY_NAME TEXT, ACCOUNT_ID TEXT,
    STAGE TEXT, AMOUNT FLOAT, CLOSE_DATE DATE,
    PROBABILITY NUMBER, LEAD_SOURCE TEXT,
    CREATED_DATE DATE, LAST_MODIFIED_DATE DATE, OWNER_ID TEXT,
    _LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(), _SOURCE TEXT DEFAULT 'salesforce_api'
  )`);

  console.log('All Bronze tables created.');

  conn.destroy();
  console.log('\nDone!');
}

run().catch(err => { console.error('Error:', err.message); process.exit(1); });
